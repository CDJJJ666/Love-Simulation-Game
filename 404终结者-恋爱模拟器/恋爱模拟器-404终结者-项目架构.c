void endingsView(void)
{
    /* 结局图鉴：2列网格（自动按 ENDING_COUNT 排行），已解锁显示名字，未解锁显示 ??? */
    int sel = 0;                /* 当前选中格子 0~3 */
    int key;                    /* 按键 */
    int i, row, coln;           /* 循环、行列 */
    int bx, by;                 /* 格子左上角 */
    const int GW = 22, GH = 5;  /* 格子宽高 */

    while (1) {
        clear(0, 0, SCREEN_W, SCREEN_H);
        setPrintColor(COL_TITLE);
        gotoXY(44, 2);                          /* 居中标题 */
        printf("[ 结局图鉴 ]");
        setPrintColor(COL_NORMAL);

        /* 网格按 ENDING_COUNT 自动排行：每行 4 格（7 个结局排成 4+3 两行） */
        for (i = 0; i < ENDING_COUNT; i++) {
            row = i / 4;  coln = i % 4;
            bx = 2 + coln * 24;
            by = 5 + row * 8;

            /* 边框 */
            setPrintColor(COL_TITLE);
            gotoXY(bx, by); printf("+");
            for (int k = 0; k < GW - 2; k++) printf("-");
            printf("+");
            for (int k = 1; k < GH - 1; k++) {
                gotoXY(bx, by + k); printf("|");
                gotoXY(bx + GW - 1, by + k); printf("|");
            }
            gotoXY(bx, by + GH - 1); printf("+");
            for (int k = 0; k < GW - 2; k++) printf("-");
            printf("+");

            /* 内容：解锁显示名字，未解锁显示 ??? */
            gotoXY(bx + 2, by + 2);
            if (i == sel) setPrintColor(COL_SELECT);   /* 选中高亮 */
            else          setPrintColor(COL_NORMAL);
            if (g_unlocked[i] == 1)
                printf("结局%d：%s", i + 1, g_endName[i]);
            else
                printf("结局%d：???", i + 1);
            setPrintColor(COL_NORMAL);
        }

        /* 底部提示 */
        setPrintColor(COL_YELLOW);
        gotoXY(35, 28);
        printf("a/d 移动光标  回车查看文案  ESC 返回");
        setPrintColor(COL_NORMAL);

        /* 按键 */
        key = _getch();
        if (key == 0 || key == 224) key = _getch();   /* 方向键两字节：先吃掉前缀 */
        if (key == 'a' || key == 'A' || key == 75)       sel = (sel + ENDING_COUNT - 1) % ENDING_COUNT;  /* 左移（上一格） */
        else if (key == 'd' || key == 'D' || key == 77)  sel = (sel + 1) % ENDING_COUNT;  /* 右移（下一格） */
        else if (key == 13 || key == ' ') {                        /* 回车查看 */
            if (g_unlocked[sel] == 1) {
                clear(0, 0, SCREEN_W, SCREEN_H);
                setPrintColor(COL_TITLE);
                gotoXY(44, 6);
                printf("结局%d：%s", sel + 1, g_endName[sel]);
                setPrintColor(COL_NORMAL);
                gotoXY(21, 9);
                printf("%s", g_endText[sel]);
                gotoXY(46, 28);
                printf("按任意键返回");
                _getch();
            }
            else {
                setPrintColor(COL_RED);
                gotoXY(43, 30);
                printf("该结局尚未解锁！");
                setPrintColor(COL_NORMAL);
                _getch();
            }
        }
        else if (key == 27) return;  /* ESC 返回 */
    }
}