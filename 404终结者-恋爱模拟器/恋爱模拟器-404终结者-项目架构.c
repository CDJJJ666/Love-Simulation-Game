int  eventPick(void)
{/* 如果存在激活的十年长剧情链，并且进度1‑9，计算返回对应后续事件ID */
    if (g_activeChain != -1 && g_chainStep >= 1 && g_chainStep <= 9)
    {
        int ch = g_activeChain;
        int st = g_chainStep;
        int followEv = 8 + ch * 9 + (st - 1);   /* 每条链9个后续事件：链i = 8+i*9 .. 8+i*9+8 */
        return followEv;
    }
    int valid[EVENT_COUNT];
    int count = 0;
    int i;
    /*随机池只抽取0‑7原始主事件；8‑79全部后续事件不参与随机 */
    for (i = 0; i < 8; i++) {
        if (g_evTitle[i][0] != '\0')
            valid[count++] = i;
    }
    if (count == 0)
        return -1;
    return valid[randInt(0, count - 1)];
}

int  eventExecute(int evId, int opt)
{
    int lv;                   /* 判定档位 J_* */
    int mood = g_attr[ATTR_MOOD];
    const char* lvName;       /* 档位中文名 */
    if (opt != 0 && opt != 1) opt = 0;            /* 选项越界按第 1 项 */
    /* B 选项（保守/观望/不推进）：安全选项，永不失败、不扣属性，只给微量好感 */
    if (opt == 1) {
        relAdd(g_targetNpc, 1, 0, 0);            /* 好感+1（很少），心动/信任不变 */
        mood = g_attr[ATTR_MOOD];                 /* 心情不变 */
        if (evId >= 0 && evId <= 7) { g_activeChain = evId; g_chainStep = 1; }
        if (evId >= 8) { g_chainStep += 1; if (g_chainStep >= 10) { g_activeChain = -1; g_chainStep = 0; } }
        if (mood < ATTR_MIN) mood = ATTR_MIN;
        if (mood > ATTR_MAX) mood = ATTR_MAX;
        g_attr[ATTR_MOOD] = mood;
        relRefresh(g_targetNpc);
        g_lastScore = g_attr[g_evAttr[evId][opt]] * 5 + g_favor[g_targetNpc] * 6 / 5;
        sprintf(g_lastMsg, "%s 判定：稳妥（保守观望，好感+1）", g_evTitle[evId]);
        return J_OK;
    }
    /* 1. 调 eventCheck：score = g_attr[判定属性]*5 + g_favor[主攻]*6/5，按分数线分档 */
    lv = eventCheck(g_evAttr[evId][opt], g_targetNpc, g_evLine[evId][opt]);
    /* 2. 成功档/失败档分别读表：好感增量 + 心情增量 */
    if (lv == J_OK || lv == J_BIGOK) {
        relAdd(g_targetNpc, g_evOkFavor[evId][opt], 3, 0);
        mood = g_attr[ATTR_MOOD] + g_evOkMood[evId][opt];

        /* 主事件0‑7判定成功 → 开启长剧情链 */
        if (evId >= 0 && evId <= 7)
        {
            g_activeChain = evId;
            g_chainStep = 1;
        }
        if (evId >= 8)
        {
            g_chainStep += 1;
            // step到10，整条链结束
            if (g_chainStep >= 10)
            {
                g_activeChain = -1;
                g_chainStep = 0;
            }
        }
    }
    else {
        relAdd(g_targetNpc, g_evNoFavor[evId][opt], 0, 0);
        mood = g_attr[ATTR_MOOD] + g_evNoMood[evId][opt];
    }
    /* 3. 心情钳制 1~10 */
    if (mood < ATTR_MIN) mood = ATTR_MIN;
    if (mood > ATTR_MAX) mood = ATTR_MAX;
    g_attr[ATTR_MOOD] = mood;
    /* 4. 刷新该 NPC 关系阶段 */
    relRefresh(g_targetNpc);
    /* 5. 结果文案写 g_lastMsg（档位中文名 + 分数） */
    switch (lv) {
    case J_BIGOK: lvName = "大成功"; break;
    case J_OK:    lvName = "成功";   break;
    case J_FAIL:  lvName = "失败";   break;
    default:      lvName = "大失败"; break;
    }
    sprintf(g_lastMsg, "%s 判定：%s（%d分）", g_evTitle[evId], lvName, g_lastScore);
    return lv;
}

int  doAction(int actId, int npc)
{
    int i;                    /* 循环变量 */
    int ap;                   /* 本行动消耗行动点 */
    int need;                 /* 是否需要选 NPC */
    int favor;                /* 本次好感增量（含偏好加成） */
    const char* actName;      /* 行动名（拼文案用） */

    if (actId < 0 || actId >= ACT_COUNT) { strcpy(g_lastMsg, "未知行动"); return 0; }
    actName = g_actName[actId];

    /* 1. 校验一：行动点够不够 */
    ap = g_actAp[actId];
    if (g_ap < ap) { strcpy(g_lastMsg, "行动点不足"); return 0; }

    /* 2. 校验二：需要目标的行动必须已选 NPC */
    need = g_actNeedNpc[actId];
    if (need && (npc < 0 || npc >= NPC_COUNT)) { strcpy(g_lastMsg, "请先选择一位NPC"); return 0; }

    /* 3. 校验三：特殊行动的关系前提 */
    if (actId == ACT_CONFESS) {
        if (g_rel[npc] == REL_STRANGER || g_rel[npc] == REL_LOVER || g_rel[npc] == REL_BROKEN) {
            strcpy(g_lastMsg, "当前关系无法告白（仅朋友/暧昧可告白）"); return 0;
        }
    }
    else if (actId == ACT_BREAKUP) {
        if (g_rel[npc] != REL_LOVER) {
            strcpy(g_lastMsg, "只有恋人才能分手"); return 0;
        }
    }
    else if (actId == ACT_COLDWAR) {
        if (g_rel[npc] == REL_STRANGER) {
            strcpy(g_lastMsg, "陌生人不能冷战"); return 0;
        }
    }

    /* 4. 扣行动点，按 g_actAttr 改三属性（钳制 1~10） */
    g_ap -= ap;
    for (i = 0; i < 3; i++) {
        int v = g_attr[i] + g_actAttr[actId][i];
        if (v < ATTR_MIN) v = ATTR_MIN;
        if (v > ATTR_MAX) v = ATTR_MAX;
        g_attr[i] = v;
    }

    /* 5. 需要目标的行动：加好感；NPC 偏好属性 >=8 时"投其所好"额外 +2
          告白/分手/冷战跳过这里：它们在第 6 步由 relConfess/relBreakup/relColdWar 独立结算，
          若这里也 relAdd，信任等数值会被重复扣减 */
    if (need && actId != ACT_CONFESS && actId != ACT_BREAKUP && actId != ACT_COLDWAR) {
        int trustAdd = g_actTrust[actId]; // ← 读取本行动信任增量
        favor = g_actFavor[actId];
        if (g_attr[g_npcLike[npc]] >= 8)
            favor += 2;
        relAdd(npc, favor, g_actHeart[actId], trustAdd); // ← 好感/心动/信任真正加到NPC身上
    }

    /* 6. 告白/分手/冷战三个特殊行动单独结算 */
    if (actId == ACT_CONFESS) {
        if (relConfess(npc))
            strcpy(g_lastMsg, "告白成功！TA 答应了你的心意！");
        else
            strcpy(g_lastMsg, "告白失败……再接再厉吧");
    }
    else if (actId == ACT_BREAKUP) {
        relBreakup(npc);
        g_earlyEnd = 2;         /* 标记：因分手提前结束 */
        strcpy(g_lastMsg, "你们分手了……");
    }
    else if (actId == ACT_COLDWAR) {
        relColdWar(npc);
        g_earlyEnd = 1;         /* 标记：因冷战提前结束 */
        strcpy(g_lastMsg, "你们冷战了……");
    }
    else {
        /* 普通行动：拼接结果文案 */
        if (need && g_actFavor[actId] != 0)
        {
            int addFavor = g_actFavor[actId] + (g_attr[g_npcLike[npc]] >= 8 ? 2 : 0);
            int addTrust = g_actTrust[actId];
            int addHeart = g_actHeart[actId];
            if (addTrust > 0 && addHeart > 0)
            {
                sprintf(g_lastMsg, "%s: 与%s好感+%d，心动+%d，信任+%d", actName, g_npcName[npc], addFavor, addHeart, addTrust);
            }
            else if (addTrust > 0)
            {
                sprintf(g_lastMsg, "%s: 与%s好感+%d，信任+%d", actName, g_npcName[npc], addFavor, addTrust);
            }
            else
            {
                sprintf(g_lastMsg, "%s: 与%s好感+%d", actName, g_npcName[npc], addFavor);
            }
        }
        else
        {
            sprintf(g_lastMsg, "%s完成", actName);
        }
    }
    /* 7. 全部 NPC 刷新关系阶段 */
    for (i = 0; i < NPC_COUNT; i++)
        relRefresh(i);

    return 1;
}


int eventView(int evId)
{
    static const int W = 60;  /* 正文显示宽度（列） */
    int opt = 0;              /* 当前选中选项 0/1 */
    int key;                  /* 按键值 */
    int lv;                   /* 判定档位 */
    int x, y;                 /* 正文打印起点 */
    int col;                  /* 当前行已占列数 */
    const char* p;            /* 正文游标 */
    const char* name;         /* 档位中文名 */
    int lines;                /* 正文折行后的总行数（数行用） */

redo:                                             /* 暂停选"继续"后重画整个事件界面 */
    clear(1, 1, SCREEN_W - 2, SCREEN_H - 2);   /* 清屏（矩形清空） */


    /* 标题（居中，亮青色） */
    setPrintColor(COL_TITLE);
    gotoXY((SCREEN_W - 20) / 2 + 1, 3);
    printf("%s", g_evTitle[evId]);

    /* 正文：UTF-8 逐字符折行打印（中文按 2 列，最多 16 行） */
    setPrintColor(COL_NORMAL);
    x = (SCREEN_W - W) / 2 + 1;

    /* 先数一遍：这段文本折行后共几行（和下面打印用同一套规则） */
    lines = 1; col = 0;
    for (p = g_evText[evId]; *p != '\0'; ) {
        if ((unsigned char)*p >= 0x80) {
            if (col + 2 > W) { lines++; col = 0; }
            col += 2; p += 3;
        }
        else {
            if (col + 1 > W) { lines++; col = 0; }
            col += 1; p += 1;
        }
    }

    y = 5 + (16 - lines) / 2; col = 0;   /* 在 y=5~20 区间内垂直居中 */
    gotoXY(x, y);
    for (p = g_evText[evId]; *p != '\0' && y <= 20; ) {
        int isCn = ((unsigned char)*p >= 0x80);   /* 高位字节 = 中文 */
        if (isCn) {
            if (col + 2 > W) { y++; col = 0; gotoXY(x, y); }   /* 汉字占 2 列 */
            putchar(p[0]); putchar(p[1]); putchar(p[2]);       /* 一次输出 3 字节 */
            col += 2;
            p += 3;                                            /* 跳过整个汉字 */
        }
        else {
            if (col + 1 > W) { y++; col = 0; gotoXY(x, y); }
            putchar(*p);
            col += 1;
            p += 1;
        }
    }


    /* 两个选项（黄色；选中项黄底黑字高亮）；右侧标注成功率提示 */
    for (;;) {
        /* A 选项（主动）按真实判定公式估算成功率：score=属性*5+好感*6/5 */
        int npcForRate = g_targetNpc;
        int s0 = g_attr[g_evAttr[evId][0]] * 5 + g_favor[npcForRate] * 6 / 5;
        int pct0 = (s0 - (g_evLine[evId][0] - 25)) * 2;
        if (pct0 < 5) pct0 = 5;
        if (pct0 > 95) pct0 = 95;

        gotoXY((SCREEN_W - 40) / 2 + 1, 22);
        setPrintColor(opt == 0 ? COL_SELECT : COL_YELLOW);
        printf("1.%s", g_evOpt[evId][0]);
        gotoXY((SCREEN_W - 40) / 2 + 1 + 30, 22);
        setPrintColor(pct0 >= 50 ? COL_GREEN : COL_RED);
        printf("成功率%d%%   ", pct0);

        gotoXY((SCREEN_W - 40) / 2 + 1, 23);
        setPrintColor(opt == 1 ? COL_SELECT : COL_YELLOW);
        printf("2.%s", g_evOpt[evId][1]);
        gotoXY((SCREEN_W - 40) / 2 + 1 + 30, 23);
        setPrintColor(COL_GREEN);
        printf("稳妥无风险   ");
        setPrintColor(COL_NORMAL);

        gotoXY((SCREEN_W - 40) / 2 + 1, 25);
        setPrintColor(COL_NORMAL);
        printf("a/d 或 1/2 选择，回车确认（ESC 默认第1项）");

        // 先清空提示行，防止旧提示残留
        gotoXY((SCREEN_W - 60) / 2 + 1, 26);
        printf("                                                            ");

        key = _getch();

        if (key == 'a' || key == 'A' || key == '1') opt = 0;
        else if (key == 'd' || key == 'D' || key == '2') opt = 1;
        else if (key == '\r') break;          /* 回车确认 */
        else if (key == 27) {                    /* ESC：弹出暂停面板 */
            if (pauseView() == 1)
                goto redo;                       /* 选"继续游戏"：重画界面继续选 */
            else {
                clear(0, 0, SCREEN_W, SCREEN_H);
                return 0;                        /* 选"返回主菜单"：退出事件并回主菜单 */
            }
        }
    }

    /* 结算并显示结果：成功绿字、失败红字 */
    lv = eventExecute(evId, opt);
    switch (lv) {
    case J_BIGOK: name = "大成功"; break;
    case J_OK:    name = "成功";   break;
    case J_FAIL:  name = "失败";   break;
    default:      name = "大失败"; break;
    }
    gotoXY((SCREEN_W - 60) / 2 + 1, 27);
    setPrintColor((lv == J_OK || lv == J_BIGOK) ? COL_GREEN : COL_RED);
    printf("判定结果：%s（%d分）", name, g_lastScore);
    gotoXY((SCREEN_W - 60) / 2 + 1, 28);
    setPrintColor(COL_NORMAL);
    printf("%s", g_lastMsg);

    /* 成功/失败对应的属性增减明细 */
    gotoXY((SCREEN_W - 60) / 2 + 1, 29);
    {
        int isOk = (lv == J_OK || lv == J_BIGOK);
        int fav, heartAdd, moodAdd;
        if (opt == 1) {   /* B 保守选项：固定微量好感，不动心动/心情 */
            fav = 1; heartAdd = 0; moodAdd = 0;
        } else {
            fav = isOk ? g_evOkFavor[evId][0] : g_evNoFavor[evId][0];
            heartAdd = isOk ? 3 : 0;
            moodAdd = isOk ? g_evOkMood[evId][0] : g_evNoMood[evId][0];
        }
        char buf[90];
        int len = 0;
        if (fav != 0)      len += sprintf(buf + len, "好感%+d ", fav);
        if (heartAdd != 0) len += sprintf(buf + len, "心动%+d ", heartAdd);
        if (moodAdd != 0)  len += sprintf(buf + len, "心情%+d", moodAdd);
        if (len == 0)      strcpy(buf, "无属性变化");
        setPrintColor(isOk ? COL_GREEN : COL_RED);
        printf("%s：与%s %s", isOk ? "成功奖励" : "失败惩罚", g_npcName[g_targetNpc], buf);
    }
    setPrintColor(COL_NORMAL);

    gotoXY((SCREEN_W - 30) / 2 + 1, 30);
    printf("按任意键继续");
    _getch();
    clear(1, 1, SCREEN_W - 2, SCREEN_H - 2);
    return 1;                                    /* 事件正常结束，继续游戏 */
}


