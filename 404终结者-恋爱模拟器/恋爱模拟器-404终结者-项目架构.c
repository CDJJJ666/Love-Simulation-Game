int  loadGame(int slot)
{
    int i;
    int k;
    // 判断槽位是否为空
    if (g_memUsed[slot] == 0)
    {
        return 0;
    }

    // 拷贝玩家姓名，手写循环，和saveGame对应
    k = 0;
    while (k < NAME_LEN - 1 && g_memName[slot][k] != '\0')
    {
        g_name[k] = g_memName[slot][k];
        k = k + 1;
    }
    g_name[k] = '\0';

    // 年龄、年份
    g_age = g_memAge[slot];
    g_year = g_memYear[slot];

    // 三属性：金钱、魅力、心情
    for (i = 0; i < 3; i = i + 1)
    {
        g_attr[i] = g_memAttr[slot][i];
    }

    // NPC：好感、心动、信任、关系阶段
    for (i = 0; i < NPC_COUNT; i = i + 1)
    {
        g_favor[i] = g_memFavor[slot][i];
        g_heart[i] = g_memHeart[slot][i];
        g_trust[i] = g_memTrust[slot][i];
        g_rel[i] = g_memRel[slot][i];
    }

    // 主攻NPC下标
    g_targetNpc = g_memTarget[slot];
    //--------恢复剧情链状态---------
    g_activeChain = g_memActiveChain[slot];
    g_chainStep = g_memChainStep[slot];
    g_ap = g_memAp[slot];   /* 恢复剩余行动点 */
    g_yearHasEvent = g_memYearHasEvent[slot];   /* 恢复本年事件标记 */
    for (i = 0; i < NPC_COUNT; i++)
        g_everBroken[i] = g_memEverBroken[slot][i];   /* 恢复分手记录 */

    g_earlyEnd = 0;   /* 读档后清除提前结束标记，按存档进度正常游玩 */
    return 1;
}



