//waiting
void uiInit(void) { /* waiting: 控制台100x32 + 隐藏光标 + srand((unsigned)time(NULL)) */
    HANDLE hOut = GetStdHandle(STD_OUTPUT_HANDLE);
    CONSOLE_CURSOR_INFO cursor;   /* 光标信息 */
    SMALL_RECT rect;              /* 窗口矩形 */
    COORD size;                   /* 缓冲区大小 */

    /* 1. 缓冲区先撑到 100x32（窗口必须能装进缓冲区） */
    size.X = SCREEN_W;
    size.Y = SCREEN_H;
    SetConsoleScreenBufferSize(hOut, size);

    /* 2. 再把窗口大小设成 100x32（矩形是闭区间，右下角要减 1） */
    rect.Left = 0;
    rect.Top = 0;
    rect.Right = SCREEN_W - 1;
    rect.Bottom = SCREEN_H - 1;
    SetConsoleWindowInfo(hOut, TRUE, &rect);

    /* 3. 隐藏光标，避免 gotoXY 重画时闪 */
    cursor.dwSize = 1;
    cursor.bVisible = FALSE;
    SetConsoleCursorInfo(hOut, &cursor);

    /* 控制台输出用 UTF-8，中文不乱码（配合编译选项 /utf-8） */
    SetConsoleOutputCP(CP_UTF8);
    SetConsoleCP(CP_UTF8);

    /* 4. 播一次随机种子，randInt 才有随机数可用 */
    srand((unsigned)time(NULL));
}

void gotoXY(int x, int y) { /* waiting: COORD + SetConsoleCursorPosition（参考组1/3/4模板） */
    COORD c;
    c.X = x - 1;
    c.Y = y - 1;
    SetConsoleCursorPosition(GetStdHandle(STD_OUTPUT_HANDLE), c);

}

void clear(int x, int y, int w, int h) { /* waiting: 整块填充空格（API 一次性清屏，消除逐字闪烁） */
    DWORD written;                 /* 实际填充的字符数（API 要求） */
    COORD c;                       /* 清屏起点（0 起坐标） */
    if (x < 1) x = 1;   /* 兼容 0 起调用 */
    if (y < 1) y = 1;
    c.X = x - 1;
    c.Y = y - 1;
    /* 1. 整块填空格：一次 API 调用代替 3200 次 putchar，界面不再闪 */
    FillConsoleOutputCharacter(GetStdHandle(STD_OUTPUT_HANDLE), ' ', (DWORD)(w * h), c, &written);
    /* 2. 顺手把该区域颜色复位成白字黑底，防止旧颜色残留 */
    FillConsoleOutputAttribute(GetStdHandle(STD_OUTPUT_HANDLE), (WORD)COL_NORMAL, (DWORD)(w * h), c, &written);
}

void setPrintColor(int color) { /* waiting: SetConsoleTextAttribute */
    SetConsoleTextAttribute(GetStdHandle(STD_OUTPUT_HANDLE), color);

}

int  menuSelect(int x, int y, const char items[][MENU_LEN], int count, int initSel) {
    int i;              /* 菜单项循环 */
    int key;            /* 按键 */
    int sel = initSel;  /* 当前高亮项 */

    if (count <= 0)   return -1;            /* 没有菜单项，直接当 ESC 处理 */
    if (sel < 0 || sel >= count) sel = 0;   /* 初始选中越界就拉回第一项 */

    while (1) {
        /* 1. 重画整列菜单：选中项用 COL_SELECT 高亮，其余 COL_NORMAL
               %-*s 用空格补齐到 MENU_LEN-1，顺便把上一轮的长内容擦掉 */
        for (i = 0; i < count; i++) {
            gotoXY(x, y + i);
            setPrintColor(i == sel ? COL_SELECT : COL_NORMAL);
            printf("%-*s", MENU_LEN - 1, items[i]);
        }
        setPrintColor(COL_NORMAL);          /* 恢复默认色，别把高亮留在屏幕上 */

        /* 2. 收按键 */
        key = _getch();
        if (key == 0 || key == 224) {       /* 方向键是两字节，先吃掉前缀 */
            key = _getch();
            if (key == 72)      sel = (sel - 1 + count) % count;  /* ↑ */
            else if (key == 80) sel = (sel + 1) % count;          /* ↓ */
        }
        else if (key == 'w' || key == 'W')  sel = (sel - 1 + count) % count;
        else if (key == 's' || key == 'S')  sel = (sel + 1) % count;
        else if (key == 13 || key == ' ')   return sel;           /* 回车/空格确认 */
        else if (key == 27)                 return -1;            /* ESC 返回 -1 */
    }
}

//原电池
int  randInt(int lo, int hi)
{
    return rand() % (hi - lo + 1) + lo;   /* 尊重调用方范围，种子由 uiInit 播一次 */
}

int  eventCheck(int attr, int npc, int line)
{
    int score;                          /* 判定分数 */
    /* 公式：score = 判定属性*6 + 好感*6/5（只用参数 attr 指定的那一个属性） */
    score = g_attr[attr] * 5 + g_favor[npc]*6 / 5;
    g_lastScore = score;                /* 分数写中转变量 */
    if (score >= line + 25)      return J_BIGOK;
    else if (score >= line)      return J_OK;
    else if (score >= line - 25) return J_FAIL;
    else                         return J_BIGFAIL;
}

int  confessCheck(int npc)
{
    double H, T, C, M, S;       /* 各分量 0~1 */
    double Score;               /* 判定分数 0~1 */
    H = g_favor[npc] / 100.0;   /* 好感分量 */
    T = g_trust[npc] / 100.0;   /* 信任分量 */
    C = g_attr[ATTR_CHARM] / 10.0;  /* 魅力分量 */
    M = g_attr[ATTR_MONEY] / 10.0;  /* 金钱分量 */
    S = g_attr[ATTR_MOOD] / 10.0;   /* 心情分量 */
    Score = (3 * H + 2 * T + 2 * C + 3 * M + S) / 11.0;
    g_lastScore = (int)(Score * 100);   /* 分数 0~100 写中转变量 */
    return Score >= 0.7 ? 1 : 0;        /* 分界 0.7 */
}

int  endingEvaluate(void)
{
    int npc;                        /* 循环变量 */
    int Sum[NPC_COUNT];             /* 每个 NPC 的好感+心动 */
    int maxSum;                     /* 最高值 */
    int endingId;                   /* 结局 id */
    for (npc = 0; npc < NPC_COUNT; npc++)
        Sum[npc] = g_favor[npc] + g_heart[npc];
    maxSum = Sum[0];
    for (npc = 1; npc < NPC_COUNT; npc++)
    {
        if (Sum[npc] > maxSum)
        {
            maxSum = Sum[npc];
            g_targetNpc = npc;      /* 存下标，不是分数 */
        }
    }
    /* Ending1 needs lover + sum>=150; else downgrade to confidant */
    if (g_rel[g_targetNpc] == REL_LOVER && maxSum >= 150)      endingId = 1;
    else if (maxSum >= 100) endingId = 2;
    else if (maxSum >= 50)  endingId = 3;
    else                    endingId = 4;
    /* 只返回结局 id，不在这里解锁图鉴——是否新解锁由 settlementView 判断并置位 */
    return endingId;
}

//北海
void relAdd(int npc, int df, int dh, int dt) {
    /* 好感增量，钳制 0~100 */
    g_favor[npc] += df;
    if (g_favor[npc] < 0)        g_favor[npc] = 0;
    if (g_favor[npc] > STAT_MAX) g_favor[npc] = STAT_MAX;

    /* 心动增量，钳制 0~100 */
    g_heart[npc] += dh;
    if (g_heart[npc] < 0)        g_heart[npc] = 0;
    if (g_heart[npc] > STAT_MAX) g_heart[npc] = STAT_MAX;

    /* 信任增量，钳制 0~100 */
    g_trust[npc] += dt;
    if (g_trust[npc] < 0)        g_trust[npc] = 0;
    if (g_trust[npc] > STAT_MAX) g_trust[npc] = STAT_MAX;
}

void relRefresh(int npc)
{
    /* 1. 崩盘判定：恋人 且 信任<10 → 分手 */
    if (g_rel[npc] == REL_LOVER && g_trust[npc] < 10)
    {
        g_everBroken[npc] = 1;
        g_rel[npc] = REL_BROKEN;
        return;
    }

    /* 2. 分手后：好感回到 40 以上，恢复朋友 */
    if (g_rel[npc] == REL_BROKEN && g_favor[npc] >= 40)
    {
        g_rel[npc] = REL_FRIEND;
    }

    /* 3. 陌生 → 朋友：好感 >= 25 */
    if (g_rel[npc] == REL_STRANGER && g_favor[npc] >= 25)
    {
        g_rel[npc] = REL_FRIEND;
    }

    /* 4. 朋友 → 暧昧：好感 >= 60 且 心动 >= 30 */
    if (g_rel[npc] == REL_FRIEND
        && g_favor[npc] >= 60 && g_heart[npc] >= 30)
    {
        g_rel[npc] = REL_AMBIG;
    }

}

int relConfess(int npc)
{
    int ok;
    ok = confessCheck(npc);

    if (ok)
    {
        /* 告白成功：关系置恋人 */
        g_rel[npc] = REL_LOVER;

        /* 好感+5、心动+10、信任+5 */
        relAdd(npc, 5, 10, 5);

        /* 心情+2，钳制上限 */
        g_attr[ATTR_MOOD] = g_attr[ATTR_MOOD] + 2;
        if (g_attr[ATTR_MOOD] > ATTR_MAX)
        {
            g_attr[ATTR_MOOD] = ATTR_MAX;
        }
    }
    else
    {
        /* 告白失败：好感-5、心动-3 */
        relAdd(npc, -5, -3, 0);

        /* 心情-1，钳制下限 */
        g_attr[ATTR_MOOD] = g_attr[ATTR_MOOD] - 1;
        if (g_attr[ATTR_MOOD] < ATTR_MIN)
        {
            g_attr[ATTR_MOOD] = ATTR_MIN;
        }
    }

    relRefresh(npc);
    return ok;
}

